-- 6. Verification Output
SELECT 
    p.company_name,
    u.email,
    p.id AS user_uuid,
    (SELECT COUNT(*) FROM public.campaign_data c WHERE c.company_name = p.company_name) AS campaign_rows,
    (SELECT SUM(leads) FROM public.campaign_data c WHERE c.company_name = p.company_name) AS total_leads
FROM public.profiles p
JOIN auth.users u ON p.id = u.id;
