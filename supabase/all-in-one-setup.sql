-- 1. Create Tables
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    company_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT company_name_not_empty CHECK (length(trim(company_name)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_profiles_company_name ON public.profiles(company_name);

CREATE TABLE IF NOT EXISTS public.campaign_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name TEXT NOT NULL,
    channel TEXT NOT NULL,
    leads INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT leads_non_negative CHECK (leads >= 0),
    CONSTRAINT channel_not_empty CHECK (length(trim(channel)) > 0),
    CONSTRAINT campaign_company_not_empty CHECK (length(trim(company_name)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_campaign_data_company ON public.campaign_data(company_name);
CREATE INDEX IF NOT EXISTS idx_campaign_data_company_channel ON public.campaign_data(company_name, channel);

-- 2. Privileges
REVOKE ALL ON TABLE public.profiles FROM anon, public;
REVOKE ALL ON TABLE public.campaign_data FROM anon, public;

GRANT SELECT, INSERT ON TABLE public.profiles TO authenticated;
GRANT SELECT ON TABLE public.campaign_data TO authenticated;

-- 3. Row-Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles FORCE ROW LEVEL SECURITY;

ALTER TABLE public.campaign_data ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.campaign_data FORCE ROW LEVEL SECURITY;

-- Profiles Policies
DROP POLICY IF EXISTS "Users can only read their own profile" ON public.profiles;
CREATE POLICY "Users can only read their own profile"
ON public.profiles FOR SELECT TO authenticated
USING (id = auth.uid());

DROP POLICY IF EXISTS "Users can insert their own profile" ON public.profiles;
CREATE POLICY "Users can insert their own profile"
ON public.profiles FOR INSERT TO authenticated
WITH CHECK (id = auth.uid());

-- Campaign Data Policy
DROP POLICY IF EXISTS "Users can only read their own company campaigns" ON public.campaign_data;
CREATE POLICY "Users can only read their own company campaigns"
ON public.campaign_data FOR SELECT TO authenticated
USING (
    company_name = (
        SELECT p.company_name
        FROM public.profiles p
        WHERE p.id = auth.uid()
    )
);

