-- ==============================================================================
-- INSIGRA REPORTS - DATABASE SCHEMA
-- Multi-Tenant Marketing Analytics Platform
-- ==============================================================================

-- 1. Profiles Table
-- Maps authenticated Supabase Auth users (auth.users) to their tenant/organization.
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    company_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT company_name_not_empty CHECK (length(trim(company_name)) > 0)
);

-- Index for fast company lookups
CREATE INDEX IF NOT EXISTS idx_profiles_company_name ON public.profiles(company_name);

-- 2. Campaign Data Table
-- Stores marketing campaign performance by tenant and channel.
CREATE TABLE IF NOT EXISTS public.campaign_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name TEXT NOT NULL,
    channel TEXT NOT NULL,
    leads INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT leads_non_negative CHECK (leads >= 0),
    CONSTRAINT channel_not_empty CHECK (length(trim(channel)) > 0),
    CONSTRAINT campaign_company_not_empty CHECK (length(trim(company_name)) > 0)
);

-- Indexes for tenant-scoped querying and aggregation
CREATE INDEX IF NOT EXISTS idx_campaign_data_company ON public.campaign_data(company_name);
CREATE INDEX IF NOT EXISTS idx_campaign_data_company_channel ON public.campaign_data(company_name, channel);

-- 3. Minimum Necessary Permissions
-- Revoke all permissions from public/anonymous roles on these tables.
REVOKE ALL ON TABLE public.profiles FROM anon, public;
REVOKE ALL ON TABLE public.campaign_data FROM anon, public;

-- Grant minimal SELECT permissions to authenticated users.
-- Normal users cannot insert, update, or delete profiles or campaign_data.
GRANT SELECT ON TABLE public.profiles TO authenticated;
GRANT SELECT ON TABLE public.campaign_data TO authenticated;
